import { existsSync } from "node:fs";
import { copyFile, mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { loadScenarios, type CheckResult } from "@plugforge/bench";
import type { PluginSpec } from "../spec/spec.ts";
import { manualFileName } from "../stages/manual.ts";
import { specGaps, specLanguage, type UntestedItem } from "../stages/reporter.ts";
import type { PhaseOutcome } from "./orchestrator.ts";

export interface Delivery {
  /** The plugin jar the user installs: `<project>/dist/<Name>-<version>.jar`. */
  jar: string;
  readme: string;
  /** The full user manual next to the jar, when one was written. */
  manual?: string;
  /** What the README lists as not covered by tests. */
  untested: UntestedItem[];
}

interface ReadmeFacts {
  spec: PluginSpec;
  jarName: string;
  paperVersion: string;
  tests: { passed: number; total: number };
  coverage?: Record<string, string[]>;
  untested: UntestedItem[];
  /** Scenarios bots played on a real server; undefined when L2 did not run. */
  live?: { id: string; covers: string[]; description?: string }[];
  /** Scenario files exist but were not played. */
  liveNotRun?: number;
  /** Build phases of a phased build. */
  phases?: PhaseOutcome[];
  /** File name of the manual in dist/, when there is one. */
  manualName?: string;
}

/** Reporter output kept with the project, so `check` (no model) can still write the section. */
const reportFile = (projectDir: string) => path.join(projectDir, ".plugforge", "report.json");
/** Build phases recorded at the last delivery; undefined for projects delivered before phases were kept. */
export async function readPhaseHistory(projectDir: string): Promise<PhaseOutcome[] | undefined> {
  if (!existsSync(reportFile(projectDir))) return undefined;
  const report = JSON.parse(await readFile(reportFile(projectDir), "utf8")) as { phases?: PhaseOutcome[] };
  return report.phases?.length ? report.phases : undefined;
}

/** The last written manual, so `check` (no model) can put it back into dist/. */
const manualFile = (projectDir: string) => path.join(projectDir, ".plugforge", "manual.md");

/** First line of a generated README; PlugForge only overwrites READMEs that still start with it. */
const GENERATED_MARK = "<!-- Generated by PlugForge from spec.json; remove this line to keep your own edits. -->";


function table(head: string[], rows: string[][]): string {
  const esc = (s: string) => s.replaceAll("|", "\\|").replaceAll("\n", " ");
  return [`| ${head.join(" | ")} |`, `|${head.map(() => "---").join("|")}|`, ...rows.map((r) => `| ${r.map(esc).join(" | ")} |`)].join("\n");
}

/** README for the person who asked for the plugin, in their language (Russian or English). */
export function renderReadme(f: ReadmeFacts): string {
  const s = f.spec;
  const R = specLanguage(s) === "ru";
  const t = R
    ? {
        manual: (n: string) => `Полная инструкция для игроков и администратора — в \`dist/${n}\`.`,
        phases: "Этапы сборки",
        phasesText: "Плагин собирался по этапам; каждый следующий строился поверх готового, тесты прошлых этапов прогонялись как регрессия.",
        phaseHead: ["#", "Этап", "Статус", "Критерии"],
        phaseStatus: { done: "готов", failed: "не удался — откат к предыдущему", not_started: "не начат" },
        untested: "Не проверено автотестами",
        untestedText:
          "Автотесты выше проходят, но кое-что они не доказывают. Перед запуском на живом сервере проверьте это руками (первыми — с высоким риском):",
        untestedHead: ["Риск", "Что", "Где"],
        risk: { high: "высокий", medium: "средний", low: "низкий" },
        untestedNone: "Аудит не нашёл поведения, которое не покрыто тестами.",
        liveText: (n: number) => `Живые тесты: боты сыграли ${n} сценари${n === 1 ? "й" : n < 5 ? "я" : "ев"} на настоящем сервере Paper, все прошли:`,
        liveNotRun: (n: number) => `Живые тесты (${n} сценари${n === 1 ? "й" : n < 5 ? "я" : "ев"} в \`src/test/scenarios\`) не запускались — плагин в игре не проверен.`,
        install: "Установка",
        installText: `1. Скопируйте \`dist/${f.jarName}\` в папку \`plugins/\` сервера.\n2. Перезапустите сервер (не используйте /reload).\n3. ${s.config?.length ? "При первом запуске появится `plugins/" + s.name + "/config.yml` — настройки ниже." : "Настраивать ничего не нужно."}`,
        requires: `Требуется: Paper ${f.paperVersion} (проверено на нём), Java 21.`,
        commands: "Команды",
        cmdHead: ["Команда", "Что делает", "Право"],
        everyone: "все",
        permissions: "Права",
        permHead: ["Право", "По умолчанию", "Описание"],
        config: "Настройки (config.yml)",
        cfgHead: ["Ключ", "По умолчанию", "Тип", "Описание"],
        checked: "Что проверено",
        checkedText: `Агент PlugForge проверил плагин ${f.tests.passed} из ${f.tests.total} автотестами (JUnit + MockBukkit, без запуска настоящего сервера). Критерии приёмки:`,
        assumptions: "Допущения",
        assumptionsText: "Решения, которые агент принял сам, потому что в запросе этого не было:",
        rebuild: "Пересборка",
        rebuildText: "Исходники лежат в `src/`, спецификация — в `spec.json`. Собрать и проверить заново:",
      }
    : {
        manual: (n: string) => `The full guide for players and the administrator is in \`dist/${n}\`.`,
        phases: "Build phases",
        phasesText: "The plugin was built in phases; each one on top of the previous, with the earlier tests replayed as regression.",
        phaseHead: ["#", "Phase", "Status", "Criteria"],
        phaseStatus: { done: "done", failed: "failed — rolled back to the previous one", not_started: "not started" },
        untested: "Not covered by tests",
        untestedText: "The tests above pass, but they do not prove the following. Check these by hand on a real server before relying on them (high risk first):",
        untestedHead: ["Risk", "What", "Where"],
        risk: { high: "high", medium: "medium", low: "low" },
        untestedNone: "The audit found no behaviour left untested.",
        liveText: (n: number) => `Live tests: bots played ${n} scenario${n === 1 ? "" : "s"} on a real Paper server, all passed:`,
        liveNotRun: (n: number) => `Live tests (${n} scenario${n === 1 ? "" : "s"} in \`src/test/scenarios\`) did not run: the plugin was not checked in the game.`,
        install: "Installation",
        installText: `1. Copy \`dist/${f.jarName}\` into the server's \`plugins/\` folder.\n2. Restart the server (do not use /reload).\n3. ${s.config?.length ? "The first start creates `plugins/" + s.name + "/config.yml`; settings are below." : "Nothing to configure."}`,
        requires: `Requires Paper ${f.paperVersion} (tested on it) and Java 21.`,
        commands: "Commands",
        cmdHead: ["Command", "What it does", "Permission"],
        everyone: "everyone",
        permissions: "Permissions",
        permHead: ["Permission", "Default", "Description"],
        config: "Settings (config.yml)",
        cfgHead: ["Key", "Default", "Type", "Description"],
        checked: "What was tested",
        checkedText: `The PlugForge agent checked the plugin with ${f.tests.passed} of ${f.tests.total} automated tests (JUnit + MockBukkit, no real server). Acceptance criteria:`,
        assumptions: "Assumptions",
        assumptionsText: "Decisions the agent made because the request did not say:",
        rebuild: "Rebuilding",
        rebuildText: "Sources are in `src/`, the specification in `spec.json`. To build and test again:",
      };

  const out: string[] = [GENERATED_MARK, `# ${s.name}`, "", s.description, "", ...(f.manualName ? [t.manual(f.manualName), ""] : []), `## ${t.install}`, "", t.installText, "", t.requires, ""];
  if (f.phases && f.phases.length > 1) {
    const rows = f.phases.map((p, i) => [
      String(i + 1),
      p.title,
      p.status === "failed" && p.reason ? `${t.phaseStatus.failed} (${p.reason})` : t.phaseStatus[p.status],
      p.criteria.join(", ") || "—",
    ]);
    out.push(`## ${t.phases}`, "", t.phasesText, "", table(t.phaseHead, rows), "");
  }
  if (s.commands.length) {
    // Specs written before checksPermission existed cannot tell "open to everyone" from "checked
    // in code"; show a dash rather than claim the command is open.
    const who = (c: PluginSpec["commands"][number]) =>
      c.permission ?? c.checksPermission ?? (s.permissions?.length && !s.commands.some((x) => x.checksPermission) ? "—" : t.everyone);
    out.push(`## ${t.commands}`, "", table(t.cmdHead, s.commands.map((c) => [`\`${c.usage}\``, c.description, who(c)])), "");
  }
  if (s.permissions?.length) {
    out.push(`## ${t.permissions}`, "", table(t.permHead, s.permissions.map((p) => [`\`${p.node}\``, p.default, p.description ?? ""])), "");
  }
  if (s.config?.length) {
    out.push(`## ${t.config}`, "", table(t.cfgHead, s.config.map((c) => [`\`${c.key}\``, `\`${JSON.stringify(c.default)}\``, c.type, c.description ?? ""])), "");
  }
  out.push(`## ${t.checked}`, "", t.checkedText, "");
  for (const a of s.acceptance) out.push(`- **${a.id}** ${a.text}${f.coverage?.[a.id]?.length ? ` — \`${f.coverage[a.id]!.join("`, `")}\`` : ""}`);
  if (f.live?.length) {
    out.push("", t.liveText(f.live.length), "");
    for (const sc of f.live) out.push(`- \`${sc.id}\` (${sc.covers.join(", ")})${sc.description ? ` — ${sc.description}` : ""}`);
  } else if (f.liveNotRun) {
    out.push("", t.liveNotRun(f.liveNotRun));
  }
  out.push("", `## ${t.untested}`, "");
  if (f.untested.length) {
    const order = { high: 0, medium: 1, low: 2 };
    const rows = [...f.untested].sort((a, b) => order[a.risk] - order[b.risk]).map((u) => [t.risk[u.risk], u.what, u.where === "spec" ? "spec.json" : `\`${u.where}\``]);
    out.push(t.untestedText, "", table(t.untestedHead, rows), "");
  } else {
    out.push(t.untestedNone, "");
  }
  if (s.assumptions?.length) {
    out.push(`## ${t.assumptions}`, "", t.assumptionsText, "", ...s.assumptions.map((a) => `- ${a}`), "");
  }
  out.push(`## ${t.rebuild}`, "", t.rebuildText, "", "```", "npm run cli -- check <this folder>", "```", "");
  return out.join("\n");
}

/**
 * Hands the result to the user once L0+L1 are green: the jar goes to `dist/` (build/ is
 * Gradle's scratch space) and a README explains installation, commands and what was tested.
 */
export async function deliver(
  projectDir: string,
  spec: PluginSpec,
  check: CheckResult,
  opts: {
    paperVersion: string;
    coverage?: Record<string, string[]>;
    /** Fresh Reporter findings; without them the last saved report (or the spec gaps alone) is used. */
    untested?: UntestedItem[];
    phases?: PhaseOutcome[];
    /** A freshly written manual; without it the last saved one (if any) is used. */
    manual?: string;
  },
): Promise<Delivery> {
  let untested = opts.untested;
  if (untested) {
    await mkdir(path.dirname(reportFile(projectDir)), { recursive: true });
    // Phases are kept so a later `improve` continues the numbering and the README history.
    await writeFile(reportFile(projectDir), `${JSON.stringify({ at: new Date().toISOString(), untested, phases: opts.phases }, null, 2)}\n`);
  } else if (existsSync(reportFile(projectDir))) {
    untested = (JSON.parse(await readFile(reportFile(projectDir), "utf8")) as { untested: UntestedItem[] }).untested;
  } else {
    untested = specGaps(spec, specLanguage(spec));
  }
  if (!check.ok || !check.build.jar) throw new Error("only a green build can be delivered");
  const dist = path.join(projectDir, "dist");
  await rm(dist, { recursive: true, force: true });
  await mkdir(dist, { recursive: true });
  const jarName = path.basename(check.build.jar);
  const jar = path.join(dist, jarName);
  await copyFile(check.build.jar, jar);

  let manualText = opts.manual;
  if (manualText) await writeFile(manualFile(projectDir), manualText);
  else if (existsSync(manualFile(projectDir))) manualText = await readFile(manualFile(projectDir), "utf8");
  const manualName = manualText ? manualFileName(specLanguage(spec)) : undefined;
  const manual = manualName ? path.join(dist, manualName) : undefined;
  if (manual) await writeFile(manual, manualText!);

  const readme = path.join(projectDir, "README.md");
  const tests = { passed: check.test?.passed ?? 0, total: check.test?.total ?? 0 };
  // A README without the mark was written or edited by the user; leave it alone.
  const existing = existsSync(readme) ? await readFile(readme, "utf8") : undefined;
  if (existing === undefined || existing.startsWith(GENERATED_MARK)) {
    const scenarios = await loadScenarios(projectDir);
    const live = check.live
      ? check.live.scenarios.map((r) => ({ id: r.id, covers: r.covers, description: scenarios.scenarios.find((x) => x.id === r.id)?.description }))
      : undefined;
    const liveNotRun = check.live ? undefined : scenarios.scenarios.length || undefined;
    await writeFile(readme, renderReadme({ spec, jarName, paperVersion: opts.paperVersion, tests, coverage: opts.coverage, untested, live, liveNotRun, phases: opts.phases, manualName }));
  }
  if ((await readdir(dist)).length !== (manual ? 2 : 1)) throw new Error(`unexpected files in ${dist}`);
  return { jar, readme, manual, untested };
}
