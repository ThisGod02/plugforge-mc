import { existsSync } from "node:fs";
import { copyFile, mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import type { CheckResult } from "@plugforge/bench";
import type { PluginSpec } from "../spec/spec.ts";

export interface Delivery {
  /** The plugin jar the user installs: `<project>/dist/<Name>-<version>.jar`. */
  jar: string;
  readme: string;
}

interface ReadmeFacts {
  spec: PluginSpec;
  jarName: string;
  paperVersion: string;
  tests: { passed: number; total: number };
  coverage?: Record<string, string[]>;
}

/** First line of a generated README; PlugForge only overwrites READMEs that still start with it. */
const GENERATED_MARK = "<!-- Generated by PlugForge from spec.json; remove this line to keep your own edits. -->";

const ru = (spec: PluginSpec) => /[\u0400-\u04ff]/.test(`${spec.description} ${Object.values(spec.messages ?? {}).join(" ")}`);

function table(head: string[], rows: string[][]): string {
  const esc = (s: string) => s.replaceAll("|", "\\|").replaceAll("\n", " ");
  return [`| ${head.join(" | ")} |`, `|${head.map(() => "---").join("|")}|`, ...rows.map((r) => `| ${r.map(esc).join(" | ")} |`)].join("\n");
}

/** README for the person who asked for the plugin, in their language (Russian or English). */
export function renderReadme(f: ReadmeFacts): string {
  const s = f.spec;
  const R = ru(s);
  const t = R
    ? {
        install: "Установка",
        installText: `1. Скопируйте \`dist/${f.jarName}\` в папку \`plugins/\` сервера.\n2. Перезапустите сервер (не используйте /reload).\n3. ${s.config?.length ? "При первом запуске появится `plugins/" + s.name + "/config.yml` — настройки ниже." : "Настраивать ничего не нужно."}`,
        requires: `Требуется: Paper ${f.paperVersion} (проверено на нём), Java 21.`,
        commands: "Команды",
        cmdHead: ["Команда", "Что делает", "Право"],
        everyone: "все",
        permissions: "Права",
        permHead: ["Право", "По умолчанию", "Описание"],
        config: "Настройки (config.yml)",
        cfgHead: ["Ключ", "По умолчанию", "Тип", "Описание"],
        checked: "Что проверено",
        checkedText: `Агент PlugForge проверил плагин ${f.tests.passed} из ${f.tests.total} автотестами (JUnit + MockBukkit, без запуска настоящего сервера). Критерии приёмки:`,
        assumptions: "Допущения",
        assumptionsText: "Решения, которые агент принял сам, потому что в запросе этого не было:",
        rebuild: "Пересборка",
        rebuildText: "Исходники лежат в `src/`, спецификация — в `spec.json`. Собрать и проверить заново:",
      }
    : {
        install: "Installation",
        installText: `1. Copy \`dist/${f.jarName}\` into the server's \`plugins/\` folder.\n2. Restart the server (do not use /reload).\n3. ${s.config?.length ? "The first start creates `plugins/" + s.name + "/config.yml`; settings are below." : "Nothing to configure."}`,
        requires: `Requires Paper ${f.paperVersion} (tested on it) and Java 21.`,
        commands: "Commands",
        cmdHead: ["Command", "What it does", "Permission"],
        everyone: "everyone",
        permissions: "Permissions",
        permHead: ["Permission", "Default", "Description"],
        config: "Settings (config.yml)",
        cfgHead: ["Key", "Default", "Type", "Description"],
        checked: "What was tested",
        checkedText: `The PlugForge agent checked the plugin with ${f.tests.passed} of ${f.tests.total} automated tests (JUnit + MockBukkit, no real server). Acceptance criteria:`,
        assumptions: "Assumptions",
        assumptionsText: "Decisions the agent made because the request did not say:",
        rebuild: "Rebuilding",
        rebuildText: "Sources are in `src/`, the specification in `spec.json`. To build and test again:",
      };

  const out: string[] = [GENERATED_MARK, `# ${s.name}`, "", s.description, "", `## ${t.install}`, "", t.installText, "", t.requires, ""];
  if (s.commands.length) {
    // Specs written before checksPermission existed cannot tell "open to everyone" from "checked
    // in code"; show a dash rather than claim the command is open.
    const who = (c: PluginSpec["commands"][number]) =>
      c.permission ?? c.checksPermission ?? (s.permissions?.length && !s.commands.some((x) => x.checksPermission) ? "—" : t.everyone);
    out.push(`## ${t.commands}`, "", table(t.cmdHead, s.commands.map((c) => [`\`${c.usage}\``, c.description, who(c)])), "");
  }
  if (s.permissions?.length) {
    out.push(`## ${t.permissions}`, "", table(t.permHead, s.permissions.map((p) => [`\`${p.node}\``, p.default, p.description ?? ""])), "");
  }
  if (s.config?.length) {
    out.push(`## ${t.config}`, "", table(t.cfgHead, s.config.map((c) => [`\`${c.key}\``, `\`${JSON.stringify(c.default)}\``, c.type, c.description ?? ""])), "");
  }
  out.push(`## ${t.checked}`, "", t.checkedText, "");
  for (const a of s.acceptance) out.push(`- **${a.id}** ${a.text}${f.coverage?.[a.id]?.length ? ` — \`${f.coverage[a.id]!.join("`, `")}\`` : ""}`);
  out.push("");
  if (s.assumptions?.length) {
    out.push(`## ${t.assumptions}`, "", t.assumptionsText, "", ...s.assumptions.map((a) => `- ${a}`), "");
  }
  out.push(`## ${t.rebuild}`, "", t.rebuildText, "", "```", "npm run cli -- check <this folder>", "```", "");
  return out.join("\n");
}

/**
 * Hands the result to the user once L0+L1 are green: the jar goes to `dist/` (build/ is
 * Gradle's scratch space) and a README explains installation, commands and what was tested.
 */
export async function deliver(
  projectDir: string,
  spec: PluginSpec,
  check: CheckResult,
  opts: { paperVersion: string; coverage?: Record<string, string[]> },
): Promise<Delivery> {
  if (!check.ok || !check.build.jar) throw new Error("only a green build can be delivered");
  const dist = path.join(projectDir, "dist");
  await rm(dist, { recursive: true, force: true });
  await mkdir(dist, { recursive: true });
  const jarName = path.basename(check.build.jar);
  const jar = path.join(dist, jarName);
  await copyFile(check.build.jar, jar);

  const readme = path.join(projectDir, "README.md");
  const tests = { passed: check.test?.passed ?? 0, total: check.test?.total ?? 0 };
  // A README without the mark was written or edited by the user; leave it alone.
  const existing = existsSync(readme) ? await readFile(readme, "utf8") : undefined;
  if (existing === undefined || existing.startsWith(GENERATED_MARK)) {
    await writeFile(readme, renderReadme({ spec, jarName, paperVersion: opts.paperVersion, tests, coverage: opts.coverage }));
  }
  if ((await readdir(dist)).length !== 1) throw new Error(`unexpected files in ${dist}`);
  return { jar, readme };
}
